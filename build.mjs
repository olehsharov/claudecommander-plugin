// Bundles the daemon (src/main.ts and everything it imports) into one ESM
// file, dist/cli.js, that runs with plain Node and nothing installed.
//
// Why fully self-contained: a `./path` plugin install runs from the source
// folder, where no npm install happens, and `daemon install` copies only
// dist/ to ~/.local/share/claudecommander/daemon. Neither place has a
// node_modules, so any import left external (firebase in particular, from
// Task 17 on) would fail there with ERR_MODULE_NOT_FOUND. Only Node's own
// builtins stay external.
//
// dist/cli.js is committed (installs never build), and packaging.test.ts
// checks a fresh build matches it byte for byte.
// It also writes the orchestrator's playbook twice from one source (see
// writeOrchestratorPlaybookFiles below).
//
// Usage: node build.mjs [--outdir dist] [--entry src/main.ts]
// --entry exists for packaging.test.ts, which bundles modules main.ts does not
// reach yet (the firebase-backed backend connection) to check they bundle
// and load just as well.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { builtinModules } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, transform } from 'esbuild';

// Generated files are written next to this script, whatever the working directory.
const pluginDirectory = dirname(fileURLToPath(import.meta.url));

const outdirFlagPosition = process.argv.indexOf('--outdir');
const outputDirectory = outdirFlagPosition > 0 ? process.argv[outdirFlagPosition + 1] : 'dist';
const entryFlagPosition = process.argv.indexOf('--entry');
const entryPoint = entryFlagPosition > 0 ? process.argv[entryFlagPosition + 1] : 'src/main.ts';

// Bundled CommonJS dependencies call require(), which does not exist in an
// ES module. This banner gives them one that resolves Node builtins.
const createRequireBanner = [
  "import { createRequire as createRequireForBundledCommonJs } from 'node:module';",
  'const require = createRequireForBundledCommonJs(import.meta.url);',
].join('\n');

const buildResult = await build({
  entryPoints: { cli: entryPoint },
  outdir: outputDirectory,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  banner: { js: createRequireBanner },
  // Builtins are external because platform is node; nothing else is.
  external: [],
  metafile: true,
  logLevel: 'warning',
});

// Fail the build if anything other than a Node builtin was left as an import,
// so a dependency can never silently become a runtime requirement.
const nodeBuiltinNames = new Set(builtinModules.flatMap((name) => [name, `node:${name}`]));
const nonBuiltinExternalImports = Object.values(buildResult.metafile.outputs)
  .flatMap((output) => output.imports)
  .filter((importRecord) => importRecord.external && !nodeBuiltinNames.has(importRecord.path))
  .map((importRecord) => importRecord.path);
if (nonBuiltinExternalImports.length > 0) {
  throw new Error(`dist/cli.js would import packages at run time: ${[...new Set(nonBuiltinExternalImports)].join(', ')}`);
}

// ---- the orchestrator playbook: one source, two generated files ----
//
// playbook/orchestrator-playbook.md is the only place the playbook text is
// written. It becomes:
//   - agents/orchestrator.md, the agent the daemon launches with
//     `--agent claudecommander:orchestrator` (the playbook is its system prompt);
//   - skills/claudecommander-orchestrator/SKILL.md, the same text as a skill,
//     which the wake note ("Load the claudecommander-orchestrator skill and
//     follow it.") loads.
// Both files are committed, because installs never build. playbooks.test.ts
// checks that each body equals the source with its placeholders filled in.
//
// The source names each tool as {{MCP_TOOL:<tool>}}; this step writes the
// full plugin-namespaced name from PLUGIN_MCP_TOOL_PREFIX in
// src/pluginMcpNames.ts, so no full tool name is ever typed by hand.

// The agent frontmatter has no `tools:` key in v1: with --agent, a narrow list
// would hide tools the orchestrator needs, and a list without Agent turns off
// subagents (plan Task 2 question 1). No `permissionMode` either: plugin agents
// ignore it, and the mode comes from the launch line.
const GENERATED_FILE_NOTE = '# Generated by build.mjs from playbook/orchestrator-playbook.md. Edit that file, then run npm run build.';

const ORCHESTRATOR_AGENT_FRONTMATTER = [
  GENERATED_FILE_NOTE,
  'name: orchestrator',
  "description: This machine's claudecommander orchestrator, a background session started by the claudecommander daemon. It reads colleagues' messages, answers questions, and asks its owner before giving anyone access to anything.",
].join('\n');

const ORCHESTRATOR_SKILL_FRONTMATTER = [
  GENERATED_FILE_NOTE,
  'name: claudecommander-orchestrator',
  "description: The playbook of the claudecommander orchestrator, the background session that answers colleagues' messages for this machine. Load it only when you are that orchestrator session, or when a note tells you to load it.",
].join('\n');

// Loads src/pluginMcpNames.ts (plain constants, no imports) without a
// TypeScript loader: esbuild strips the types, and Node imports the result.
async function loadPluginToolPrefix() {
  const typeScriptSource = readFileSync(join(pluginDirectory, 'src', 'pluginMcpNames.ts'), 'utf8');
  const { code: javaScriptSource } = await transform(typeScriptSource, { loader: 'ts', format: 'esm' });
  const namesModule = await import(`data:text/javascript;base64,${Buffer.from(javaScriptSource).toString('base64')}`);
  return namesModule.PLUGIN_MCP_TOOL_PREFIX;
}

function fillToolPlaceholders(playbookText, toolPrefix) {
  return playbookText.replace(/\{\{MCP_TOOL:([a-z_]+)\}\}/g, (_placeholder, toolName) => toolPrefix + toolName);
}

// Writes only when the text changed. Tests run this build in parallel with
// tests that read the generated files, and an unchanged file is never
// truncated under a reader.
function writeFileWhenChanged(relativePath, text) {
  const absolutePath = join(pluginDirectory, relativePath);
  if (existsSync(absolutePath) && readFileSync(absolutePath, 'utf8') === text) return;
  mkdirSync(dirname(absolutePath), { recursive: true });
  writeFileSync(absolutePath, text);
}

async function writeOrchestratorPlaybookFiles() {
  const playbookSource = readFileSync(join(pluginDirectory, 'playbook', 'orchestrator-playbook.md'), 'utf8').trim();
  const playbookBody = fillToolPlaceholders(playbookSource, await loadPluginToolPrefix());
  if (playbookBody.includes('{{')) throw new Error('playbook/orchestrator-playbook.md has a placeholder build.mjs does not know');
  writeFileWhenChanged('agents/orchestrator.md', `---\n${ORCHESTRATOR_AGENT_FRONTMATTER}\n---\n\n${playbookBody}\n`);
  writeFileWhenChanged('skills/claudecommander-orchestrator/SKILL.md', `---\n${ORCHESTRATOR_SKILL_FRONTMATTER}\n---\n\n${playbookBody}\n`);
}

await writeOrchestratorPlaybookFiles();
